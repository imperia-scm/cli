import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { readTextIfExists } from './fs-utils.mjs';
import { log } from './logging.mjs';
import { captureTrimmed } from './process-runner.mjs';

const generatedTaskLabelPrefix = 'imperiascm-cli:';
const generatedTaskDetail = 'Generated by imperiascm-cli init';
const placeholderSolutionPath = '${workspaceFolder}/path/to/Backend.sln';
const configSchemaUri = 'https://raw.githubusercontent.com/imperia-scm/cli/main/schemas/imperiascm-cli.config.schema.json';
const tasksSchemaUri = 'vscode://schemas/tasks';
const launchServicesSelectTaskLabel = 'select services to launch via imperiascm-cli';
const launchServicesPrepareTaskLabel = 'prepare services to launch via imperiascm-cli';
const launchServicesRunSelectedTaskLabel = 'run selected services via imperiascm-cli';
const launchServicesTaskLabel = 'launch services via imperiascm-cli';

function getRunServiceTaskLabel(commandName) {
  return `run service ${commandName} via imperiascm-cli`;
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function normalizePathForConfig(targetPath, workspaceFolder) {
  const relativePath = path.relative(workspaceFolder, targetPath);
  const normalizedRelativePath = relativePath.split(path.sep).join('/');

  if (!normalizedRelativePath || normalizedRelativePath === '.') {
    return '${workspaceFolder}';
  }

  return `\${workspaceFolder}/${normalizedRelativePath}`;
}

function normalizeTaskConfigPath(configPath, workspaceFolder) {
  const relativePath = path.relative(workspaceFolder, configPath);

  if (!relativePath || relativePath === '.') {
    return '${workspaceFolder}';
  }

  if (!relativePath.startsWith('..')) {
    return `\${workspaceFolder}/${relativePath.split(path.sep).join('/')}`;
  }

  return configPath;
}

function normalizeRepositoryKey(repoRoot) {
  return path.basename(repoRoot);
}

async function findSolutionFile(repoRoot) {
  try {
    const output = await captureTrimmed('git', ['-C', repoRoot, 'ls-files', '--', '*.sln'], {
      cwd: repoRoot,
      scope: 'init',
    });
    const trackedMatches = output
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(Boolean)
      .map((relativePath) => path.join(repoRoot, relativePath));

    if (trackedMatches.length > 0) {
      trackedMatches.sort((left, right) => left.localeCompare(right));
      return trackedMatches[0];
    }
  } catch {
    // Fall back to a filesystem scan when git ls-files is unavailable.
  }

  async function walk(currentPath) {
    const entries = await fs.readdir(currentPath, { withFileTypes: true });

    for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
      if (entry.name === '.git' || entry.name === 'node_modules') {
        continue;
      }

      const entryPath = path.join(currentPath, entry.name);

      if (entry.isFile() && entry.name.endsWith('.sln')) {
        return entryPath;
      }

      if (entry.isDirectory()) {
        const nestedMatch = await walk(entryPath);

        if (nestedMatch) {
          return nestedMatch;
        }
      }
    }

    return null;
  }

  return await walk(repoRoot);
}

async function detectInitContext(workspaceFolder) {
  let repoRoot;

  try {
    repoRoot = await captureTrimmed('git', ['-C', workspaceFolder, 'rev-parse', '--show-toplevel'], {
      cwd: workspaceFolder,
      scope: 'init',
    });
  } catch {
    throw new Error(`Current working directory is not inside a git repository: ${workspaceFolder}`);
  }

  repoRoot = await fs.realpath(repoRoot);
  const solutionPath = await findSolutionFile(repoRoot);

  return {
    workspaceFolder,
    repoRoot,
    repoKey: normalizeRepositoryKey(repoRoot),
    workspaceName: path.basename(workspaceFolder),
    solutionPath,
  };
}

function buildDetectedRepository(initContext) {
  return {
    key: initContext.repoKey,
    root: normalizePathForConfig(initContext.repoRoot, initContext.workspaceFolder),
    solutionPath: initContext.solutionPath
      ? normalizePathForConfig(initContext.solutionPath, initContext.workspaceFolder)
      : placeholderSolutionPath,
  };
}

function createInitialConfig(initContext) {
  return {
    $schema: configSchemaUri,
    workspace: {
      name: initContext.workspaceName,
    },
    repositories: [buildDetectedRepository(initContext)],
    services: [],
  };
}

function mergeRepositoryDefinition(repositories, detectedRepository) {
  const repositoryExists = repositories.some((repository) =>
    isPlainObject(repository)
    && (repository.key === detectedRepository.key || repository.root === detectedRepository.root));

  if (!repositoryExists) {
    repositories.push(detectedRepository);
  }
}

function mergeConfig(existingConfig, initContext) {
  if (!isPlainObject(existingConfig)) {
    throw new Error('Existing config must be a JSON object.');
  }

  const mergedConfig = structuredClone(existingConfig);

  if (!isPlainObject(mergedConfig.workspace)) {
    mergedConfig.workspace = {};
  }

  if (!mergedConfig.workspace.name) {
    mergedConfig.workspace.name = initContext.workspaceName;
  }

  if (!mergedConfig.$schema) {
    mergedConfig.$schema = configSchemaUri;
  }

  if (!Array.isArray(mergedConfig.repositories)) {
    if (mergedConfig.repositories === undefined) {
      mergedConfig.repositories = [];
    } else {
      throw new Error('Existing config.repositories must be an array.');
    }
  }

  mergeRepositoryDefinition(mergedConfig.repositories, buildDetectedRepository(initContext));

  if (!Array.isArray(mergedConfig.services)) {
    if (mergedConfig.services === undefined) {
      mergedConfig.services = [];
    } else {
      throw new Error('Existing config.services must be an array.');
    }
  }

  return mergedConfig;
}

function removeJsonComments(text) {
  let result = '';
  let inString = false;
  let isEscaped = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    const nextCharacter = text[index + 1];

    if (inString) {
      result += character;

      if (isEscaped) {
        isEscaped = false;
      } else if (character === '\\') {
        isEscaped = true;
      } else if (character === '"') {
        inString = false;
      }

      continue;
    }

    if (character === '"') {
      inString = true;
      result += character;
      continue;
    }

    if (character === '/' && nextCharacter === '/') {
      index += 2;

      while (index < text.length && text[index] !== '\n') {
        index += 1;
      }

      if (index < text.length) {
        result += text[index];
      }

      continue;
    }

    if (character === '/' && nextCharacter === '*') {
      index += 2;

      while (index < text.length - 1 && !(text[index] === '*' && text[index + 1] === '/')) {
        index += 1;
      }

      index += 1;
      continue;
    }

    result += character;
  }

  return result;
}

function removeTrailingCommas(text) {
  let result = '';
  let inString = false;
  let isEscaped = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];

    if (inString) {
      result += character;

      if (isEscaped) {
        isEscaped = false;
      } else if (character === '\\') {
        isEscaped = true;
      } else if (character === '"') {
        inString = false;
      }

      continue;
    }

    if (character === '"') {
      inString = true;
      result += character;
      continue;
    }

    if (character === ',') {
      let nextIndex = index + 1;

      while (nextIndex < text.length && /\s/.test(text[nextIndex])) {
        nextIndex += 1;
      }

      if (text[nextIndex] === '}' || text[nextIndex] === ']') {
        continue;
      }
    }

    result += character;
  }

  return result;
}

function parseJsonc(text, label) {
  try {
    return JSON.parse(removeTrailingCommas(removeJsonComments(text)));
  } catch (error) {
    throw new Error(`Existing ${label} is not valid JSON/JSONC.`);
  }
}

function buildGeneratedTask(label, args, configPathReference, options = {}) {
  const task = {
    label,
    type: 'shell',
    command: 'imp',
    args: [...args, '--config', configPathReference],
    problemMatcher: [],
    detail: generatedTaskDetail,
  };

  if (options.group) {
    task.group = options.group;
  }

  if (options.hide) {
    task.hide = true;
  }

  if (options.presentation) {
    task.presentation = options.presentation;
  }

  return task;
}

function buildGeneratedCompoundTask(label, dependsOn, options = {}) {
  const task = {
    label,
    dependsOn,
    detail: generatedTaskDetail,
  };

  if (options.dependsOrder) {
    task.dependsOrder = options.dependsOrder;
  }

  if (options.group) {
    task.group = options.group;
  }

  if (options.hide) {
    task.hide = true;
  }

  return task;
}

function normalizeTaskDependencyLabels(task) {
  if (!isPlainObject(task) || task.dependsOn === undefined) {
    return [];
  }

  if (Array.isArray(task.dependsOn)) {
    return task.dependsOn.filter((label) => typeof label === 'string');
  }

  return typeof task.dependsOn === 'string' ? [task.dependsOn] : [];
}

function sortTasksByDependencyDepth(tasks) {
  const taskEntries = tasks.map((task, index) => ({
    task,
    index,
    label: isPlainObject(task) && typeof task.label === 'string' ? task.label : null,
  }));
  const generatedLabels = new Set(taskEntries.map((entry) => entry.label).filter(Boolean));
  const depthCache = new Map();
  const visiting = new Set();

  function getTaskDepth(label) {
    if (!label || !generatedLabels.has(label)) {
      return 0;
    }

    if (depthCache.has(label)) {
      return depthCache.get(label);
    }

    if (visiting.has(label)) {
      return 0;
    }

    visiting.add(label);
    const taskEntry = taskEntries.find((entry) => entry.label === label);
    const dependencyLabels = normalizeTaskDependencyLabels(taskEntry?.task)
      .filter((dependencyLabel) => generatedLabels.has(dependencyLabel));
    const depth = dependencyLabels.length === 0
      ? 0
      : Math.max(...dependencyLabels.map((dependencyLabel) => getTaskDepth(dependencyLabel))) + 1;
    visiting.delete(label);
    depthCache.set(label, depth);
    return depth;
  }

  return [...taskEntries]
    .sort((left, right) => {
      const leftDepth = getTaskDepth(left.label);
      const rightDepth = getTaskDepth(right.label);

      if (leftDepth !== rightDepth) {
        return leftDepth - rightDepth;
      }

      return left.index - right.index;
    })
    .map((entry) => entry.task);
}

function getServiceCommandNames(config) {
  if (!Array.isArray(config.services)) {
    return [];
  }

  return config.services
    .filter((service) => isPlainObject(service) && typeof service.commandName === 'string' && service.commandName)
    .map((service) => service.commandName);
}

function buildGeneratedTasks(config, configPathReference) {
  const serviceCommandNames = getServiceCommandNames(config);
  const serviceTaskLabels = serviceCommandNames.map((commandName) => getRunServiceTaskLabel(commandName));
  const launchDependsOn = [
    launchServicesSelectTaskLabel,
    launchServicesPrepareTaskLabel,
  ];
  const tasks = [
    buildGeneratedTask(launchServicesSelectTaskLabel, ['select-services-to-launch'], configPathReference, {
      presentation: {
        clear: true,
        focus: true,
        panel: 'shared',
        showReuseMessage: false,
      },
    }),
    buildGeneratedTask(launchServicesPrepareTaskLabel, ['prepare-services-to-launch'], configPathReference, {
      hide: true,
      presentation: {
        clear: true,
        panel: 'shared',
        showReuseMessage: false,
      },
    }),
  ];

  for (const commandName of serviceCommandNames) {
    tasks.push(buildGeneratedTask(getRunServiceTaskLabel(commandName), ['launch-service', commandName], configPathReference, {
      presentation: {
        clear: true,
        panel: 'shared',
        showReuseMessage: false,
      },
    }));
  }

  if (serviceTaskLabels.length > 0) {
    tasks.push(buildGeneratedCompoundTask(launchServicesRunSelectedTaskLabel, serviceTaskLabels, {
      hide: true,
    }));
    launchDependsOn.push(launchServicesRunSelectedTaskLabel);
  }

  tasks.push(buildGeneratedCompoundTask(launchServicesTaskLabel, launchDependsOn, {
    dependsOrder: 'sequence',
    group: {
      kind: 'build',
      isDefault: true,
    },
  }));

  return sortTasksByDependencyDepth(tasks);
}

function mergeTasks(existingTasksDocument, config, configPathReference) {
  if (!isPlainObject(existingTasksDocument)) {
    throw new Error('Existing tasks.json must be a JSON object.');
  }

  const mergedTasksDocument = structuredClone(existingTasksDocument);

  if (!Array.isArray(mergedTasksDocument.tasks)) {
    if (mergedTasksDocument.tasks === undefined) {
      mergedTasksDocument.tasks = [];
    } else {
      throw new Error('Existing tasks.json tasks property must be an array.');
    }
  }

  if (typeof mergedTasksDocument.version !== 'string') {
    mergedTasksDocument.version = '2.0.0';
  }

  const manualTasks = mergedTasksDocument.tasks.filter((task) =>
    !isPlainObject(task)
    || (
      (typeof task.label !== 'string' || !task.label.startsWith(generatedTaskLabelPrefix))
      && task.detail !== generatedTaskDetail
    ));

  mergedTasksDocument.tasks = [
    ...manualTasks,
    ...buildGeneratedTasks(config, configPathReference),
  ];

  return mergedTasksDocument;
}

function parseInitArgs(args) {
  let configPath = null;
  let force = false;

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];

    if (argument === '--force') {
      force = true;
      continue;
    }

    if (argument === '--config') {
      const nextValue = args[index + 1];

      if (!nextValue) {
        throw new Error('Missing value for --config.');
      }

      configPath = nextValue;
      index += 1;
      continue;
    }

    if (argument.startsWith('--config=')) {
      configPath = argument.slice('--config='.length);
      continue;
    }

    throw new Error(`Unknown init option: ${argument}`);
  }

  return { configPath, force };
}

function createDefaultTasksDocument() {
  return {
    $schema: tasksSchemaUri,
    version: '2.0.0',
    tasks: [],
  };
}

export async function runInitCommand(args = [], options = {}) {
  const { configPath: configPathOption, force } = parseInitArgs(args);
  const workspaceFolder = await fs.realpath(path.resolve(options.cwd ?? process.cwd()));
  const configPath = path.resolve(workspaceFolder, configPathOption ?? path.join('.vscode', 'imperiascm-cli.config.json'));
  const tasksPath = path.join(workspaceFolder, '.vscode', 'tasks.json');
  const initContext = await detectInitContext(workspaceFolder);
  initContext.configPath = configPath;
  const configPathReference = normalizeTaskConfigPath(configPath, workspaceFolder);
  const existingConfigText = await readTextIfExists(configPath);
  const existingTasksText = await readTextIfExists(tasksPath);

  let mergedConfig;

  if (existingConfigText === null) {
    mergedConfig = createInitialConfig(initContext);
  } else {
    try {
      mergedConfig = mergeConfig(JSON.parse(existingConfigText), initContext);
    } catch (error) {
      if (!force) {
        throw new Error(`Unable to merge config file "${configPath}": ${error.message}`);
      }

      log('init', 'WARN', `Overwriting non-mergeable config file: ${configPath}`);
      mergedConfig = createInitialConfig(initContext);
    }
  }

  let mergedTasksDocument;

  if (existingTasksText === null) {
    mergedTasksDocument = mergeTasks(createDefaultTasksDocument(), mergedConfig, configPathReference);
  } else {
    try {
      mergedTasksDocument = mergeTasks(parseJsonc(existingTasksText, 'tasks.json'), mergedConfig, configPathReference);
    } catch (error) {
      if (!force) {
        throw new Error(`Unable to merge VS Code tasks file "${tasksPath}": ${error.message}`);
      }

      log('init', 'WARN', `Overwriting non-mergeable tasks file: ${tasksPath}`);
      mergedTasksDocument = mergeTasks(createDefaultTasksDocument(), mergedConfig, configPathReference);
    }
  }

  if (!mergedTasksDocument.$schema) {
    mergedTasksDocument.$schema = tasksSchemaUri;
  }

  await fs.mkdir(path.dirname(configPath), { recursive: true });
  await fs.mkdir(path.dirname(tasksPath), { recursive: true });
  await fs.writeFile(configPath, `${JSON.stringify(mergedConfig, null, 2)}\n`, 'utf8');
  await fs.writeFile(tasksPath, `${JSON.stringify(mergedTasksDocument, null, 2)}\n`, 'utf8');

  log('init', 'OK', `Workspace bootstrap ready at ${workspaceFolder}`);
}
